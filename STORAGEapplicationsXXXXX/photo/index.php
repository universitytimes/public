		<p class="text"><em>The University Times</em> is Ireland's largest student newspaper and the current holder of the Student Publication of the Year award. In everything we do, we strive to hold College and the Students' Union to account.</p>

<p class="text">The Photo Editor of <em>The University Times</em> is responsible for all photographic output of the newspaper, online and in print.</p>


<p class="text">While it is generally expected that the Photo Editor themselves will be an excellent photographer, a large part of the role lies with sourcing other photographers and ensuring that <em>The University Times</em> has photographers there to cover current events in Trinity and in student life, and that as much original photojournalism is featured on the pages of the newspaper, online and in print.</p>

<p class="text">Thus, candidates for this position should have strong organisational and interpersonal skills, and should expect to attend weekly news section meetings such that they are aware what events need photographing and which stories need accompanying photos. They should also expect to have to interact with editors from the features, opinion, sports, magazine and Radius sections on a daily basis, as well as very close collaboration with the Editor and Deputy Editor.</p>

<p class="text">Candidates for this position should understand that photojournalism, the type of photography that appears in newspapers, is distinct from photography in general. The Photo Editor of the <em>The University Times</em> should view themselves as journalists first and foremost – journalists that employ images in order to tell a news story in an honest, impartial way – and secondly, photographers. Thus, photographers which regularly have to rely on post-camera manipulation are not suitable for this position.</p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 100,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for this position should understand that their role will primarily be with an online focus.</p>
		
		
