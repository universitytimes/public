<p class="text">This section of the newspaper is responsible for in-depth articles that are written from a student perspective, normally about Trinity or student-related issues. Whether it is writing in detail about <a href="http://www.universitytimes.ie/?p=31189">the Students' Union's finances</a>, looking at <a href="http://www.universitytimes.ie/?p=32723">the hidden gems of Trinity</a>, or going behind the scenes of <a href="http://www.universitytimes.ie/?p=32590">Trinity's sponsored-by-Google degree</a>, the features section aims to answer questions by speaking to the people involved in something, doing the research, and pulling it all together into flowing prose.</p>

<p class="text">Typically, candidates for the positions in this section have already served as a Staff Writer or Senior Staff Writer in <em>The University Times</em> or in other student publications, or in a masthead position. Experience in national publications will be considered, but experience in Trinity student media is preferred. </p>

<p class="text">Candidates should work very well in a team, and should expect collaboration with a wide variety of journalists, whether they are writers, photographers, illustrators or editors. </p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 100,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for these positions should expect to be responsible for the production of several features articles every week, and should expect daily work and interaction with the Editor and Deputy Editor.</p>
		
		
