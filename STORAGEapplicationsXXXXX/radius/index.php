<p class="text">Radius is a new section to The University Times, and is currently hiring senior editors for the section. Radius section editors and assistant editors will be hired in the coming weeks.

Radius section management consists of the following positions:</p>


<ul class="listof">

<li>Radius Editor</li>
<li>Deputy Radius Editor</li>

</ul>

<p class="text">The introduction of a new section of <em>The University Times</em>, called Radius, is a direct response to the paper's traditionally poor coverage of society life in Trinity and cultural events in the Dublin area. Radius will cover all events &ndash; society, art, theatre, life and culture &ndash; within Trinity and in the city centre, such that it becomes the go-to place to see what’s going on. Radius will feature as a pull-out supplement in the newspaper, and will have a dedicated section of the website. Most importantly, Radius will have a focus on upcoming events, rather than only reviewing past events.</p>


<p class="text">Typically, candidates for the positions in this section will have excellent writing skills, and will understand society life in Trinity, while having a strong interest and passion for cultural events, theatre, art and the goings-on in the Dublin area.</p>

<p class="text">Candidates should work very well in a team, and should expect collaboration with a wide variety of journalists, whether they are writers, photographers, or editors. </p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 100,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for these positions should expect to be focusing the output of Radius such that there are weekly roundups, several articles a week, and such that Radius can compete with Dublin-centric publications in its coverage of local events. Candidates should expect very frequent work and interaction with the Editor and Deputy Editor.</p>
		
		
