<p class="text">This section of the newspaper is responsible for opinion articles that are written from a student perspective, normally about Trinity, student-related issues or broader issues written about from a new angle. While sometimes the section features opinion pieces about international and national issues, normally the section focuses on the things that the national or international newspapers don't already have covered.</p>

<p class="text">Typically, candidates for the positions in this section have already served as a Staff Writer, a Senior Staff Writer or as a Columnist in <em>The University Times</em> or in other student publications, or in a masthead position, primarily writing opinion pieces. Experience in national publications will be considered, but experience in Trinity student media is preferred. </p>

<p class="text">Candidates for these positions should be expected to be tested on their editing skills in particular, as the section requires a distinct ability to bring the work of new and inexperienced opinion writers up to the standard normally seen in <em>The University Times</em>.</p>

<p class="text">Candidates should work very well in a team, and should expect collaboration with a wide variety of journalists, whether they are writers, photographers, illustrators or editors. </p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 100,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for these positions should expect to be responsible for the production of up to ten opinion articles every week, and should expect daily work and interaction with the Editor and Deputy Editor.</p>
		
		
