<p class="text">This section of the newspaper is responsible for covering all the sporting activities carried out by the students and clubs of Trinity College Dublin. While the section sometimes covers national and international sport, written from a student perspective, the section will be moving more inward facing in the coming year, with the goal for it to be the go-to place for anything happening in Trinity when it comes to sport.</p>

<p class="text">Typically, candidates for the positions in this section have already written about sport or College-related news for <em>The University Times</em> or in other student publications. Experience in national publications will be considered, but experience in Trinity student media is preferred. </p>

<p class="text">Candidates for these positions should understand the workings of DUCAC and Trinity's Sports Department, and should have connections in sports clubs.</p>

<p class="text">Candidates should work very well in a team, and should expect collaboration with a wide variety of journalists, whether they are writers, photographers, or editors. </p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 100,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for these positions should expect to be responsible for the production of several articles every week, and should expect very frequent work and interaction with the Editor and Deputy Editor.</p>
		
		
