		<p class="text"><em>The University Times</em> is Ireland's largest student newspaper and the current holder of the Student Publication of the Year award. In everything we do, we strive to hold College and the Students' Union to account.</p>

<p class="text">The University Times Magazine's section management consists of the following positions:</p>


<ul class="listof">

<li>Magazine Editor</li>
<li>Deputy Magazine Editor</li>

</ul>

<p class="text">The University Times Magazine is the outward-facing section of <em>The University Times</em>, covering national political stories, national social issues, national culture stories, and international issues from a student perspective. The magazine covers the angles of these themes that aren't typically covered by national publications. In 2014, a <a href="http://www.universitytimes.ie/?p=22653">magazine interview</a> with Fine Gael councillor Darren Scully went viral and made national newspaper headlines. We sent an investigative journalist to take the <a href="http://www.universitytimes.ie/?p=26113">Scientology test</a>. This year, <a href="http://www.universitytimes.ie/?p=29033">we visited</a> the Irish Amish in Dunmore East. 


<p class="text">The magazine also features content with a national and international focus from <em>The University Times</em>'s <a href="/applications/filmtv">Film & TV</a>, <a href="/applications/food">Food</a>, <a href="/applications/fashion">Fashion</a> and <a href="/applications/music">Music</a> sections.</p>

<p class="text">Typically, candidates for the positions in this section have already written feature articles for the magazine, other student publications, or have been featured in national media. An understanding of politics in Ireland, and a grasp of cultural, social and current affairs issues is also important.</p>

<p class="text">Candidates should work very well in a team, and should expect collaboration with a wide variety of journalists, whether they are writers, photographers, or editors. </p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 100,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for these positions should expect to be focusing their content output such that it is distributed well online, and should expect very frequent work and interaction with the Editor and Deputy Editor.</p>
		
		
