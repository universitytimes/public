				<p>Notorious DMK has stalked the squares of Trinity for three years now, ruthlessly playing the societies game with his lilting northern twang, manicured stubble and designer fluorescent rain jackets. </p>
				
<p>He’s kind of like Frank Underwood in House of Cards, if Frank Underwood gave tours of Capitol Hill in his spare time in a flowing cape to American tourists, and if his main hobby was multiplying huge numbers in his head.</p>

<p>McKeating is this year’s chair of Players – College’s theatre group and one of the largest and most active societies on campus, with at least one production a week throughout the year and plenty of other activities. Donal previously ran the Players’ Fresher’s Co-op event, which has been rather limply described as “kind of like Navy SEAL training for five weeks, but for theatre people in skinny jeans who smoke rollies, and little to no actual physical activity”. After a succession of colourful and highly active chairs, McKeating will no doubt carry on the tradition of Players producing some of the most creative and engaging events on campus this year. </p>


<p>For example, Donal has vowed to eat three kilos of haggis in one sitting, washed down with three litres of brightest orange Irn-Bru, if Scotland votes for independence this Thursday. Even better, if Scotland votes no, he will sing God Save the Queen in Front Square, wearing nothing but a strategically placed Union Jack. It’s a win-win situation, and an all-round magical theatrical installation.</p>

<p>McKeating also had significant success last year, both as chair of the Central Societies Committee (the committee in charge of all societies), and as co-editor of the Piranha, where he and his partner in crime tested the limits of how many doughy, MSG-rich sweet and sour chicken balls a human can possibly ingest in one sitting. The answer? Fifteen.</p>

				
				
				
				
