				<div style="font-size: 13px;">he Trinity Twenty, now in its fifth year, profiles the twenty most influential students in Trinity College Dublin. If you’re a fresher, look out for the big cheeses swaggering for all they’re worth around Front Square, wearing at least one society hoodie, numerous wristbands and the proud tattoos that are fading nightclub stamps. For most of the entrants on this list, years of blood, sweat and tears have gone into those freshers’ bags you’re already regretting hauling around, in dark committee rooms, House 6, or even outside these four walls in central Dublin that, you’ll soon learn, contain a whole world unto itself.</div></p>


<p><div style="font-size: 13px;">There are no specific criteria for being a big dog on campus, but many of the people on this list are very impressive individuals indeed in their own diverse ways. Be it affecting the opinions of many students, running organisations with budgets of tens of thousands of euro that keep some of campus’s most exciting activities going, or simply making a lot of people’s days that much nicer, nearly everyone on this list has caught the notice of many students, and won their respect. Indeed, as a fresher you’ll soon learn that the best way to make the most out of your college experience is to do stuff you enjoy and have a bit of craic while you’re at it.</div></p>
				
				
