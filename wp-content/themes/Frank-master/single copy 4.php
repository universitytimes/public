				<h3><span style="float: left; display: block; margin-right: 7px; color: white; font-size: 20px; background: black; padding: 0px 7px 0px 7px;">1</span><span style="color: #8e1163; font-size: 20px;">Domhnall McGlacken-Byrne</span></h3>
				
				<h4><span style="color: black; font-size: 14px; padding-bottom: 4px;">TCDSU President</span></h4>
				
				
				<div style="width: 40%; float: left; padding: 0px 25px 15px 0px;">
					
					<img src="http://www.universitytimes.ie/wp-content/uploads/2014/09/dom1-781x1024.jpg" />
					
					
