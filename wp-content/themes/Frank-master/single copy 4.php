				<div>
				
				<p>It’s pretty self-explanatory why the president of the Students’ Union is a powerful figure in college: Domhnall represents the views of Trinity’s 17,000 students to the college, government and to the wider community, and acts as the primary campaigns officer and head of the SU and all of its activities, including maintaining its shops which provide outrageously cheap newspapers and chocolate bars. The president also sits on many boards and committees within the college administration.</p>
				
				
<p>But Domhnall tops the list because his role seems even more important this year. The president is mandated to campaign for LGBT rights, and McGlacken-Byrne has promised intensive voter registration drives and publicity ahead of the marriage equality referendum, which is expected to be held in spring 2015. The president has previously stated that the referendum could be won or lost based on youth turnout.</p>


<p>Domhnall also has big ideas for the union itself, including an “exciting”  four-year strategic plan for dealing with the issues like fees, emigration, unemployment, and other long-term issues that can’t be put to bed in twelve months. Domhnall is known to fully commit to whatever he does, as evidenced by the fact that he once fell asleep on the subway in New York for eight hours after a night out, calmly slumbering through rush hour and arriving home at 11 am the next morning (this is actually true). With only a ten foot walk to work everyday, there’s less chance of him falling asleep en route and more chance of him applying this determination to helping the student body.</p>


<p>The Bray man has already proved himself a force to be reckoned with. Despite having a name that has more syllables than most people’s have letters, he emerged from the depths of the health sciences building to secure 74 per cent of the vote, charming anyone he came into contact with by hanging out of a tree and skateboarding WITH A HELMET through Front Square for his campaign photos. Perhaps the lamest campaign shots ever taken, but effective nonetheless.</p>


<p>Honourable mention goes to Domhnall’s colleagues, welfare officer Ian Mooney and education officer Katie Byrne. Byrne will act as one of the most important resources for those who have academic issues in College, and Mooney is there to provide support and advice for students in the areas of mental, physical, financial and sexual health. The Timetable Tsar and the Condom King, if you will.</p>

				
				
				
				
