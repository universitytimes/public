				<p>Mortell must also be commended for her and her council’s continued challenging of traditional roles within the debating community. Historically a male-dominated environment, Sarah is the first woman to succeed another woman as president of the Phil, and has been explicit in her intent to leave another crack in the glass ceiling of college societies. Her strength is undoubtedly in marshalling the troops to keep this busy society running, and her past successes as secretary and vice-president of the Phil point to her being both well-respected collegewide and having great success in keeping the Phil at its dizzying heights. </p>

				
				
				
				
