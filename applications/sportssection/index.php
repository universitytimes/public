		<p class="text"><em>The University Times</em> is Ireland's largest student newspaper. In everything we do, we strive to hold College and Trinity College Dublin Students' Union to account.</p>

<p class="text">The Sports section of <em>The University Times</em> consists of the following positions:</p>


<ul class="listof">

<li>GAA Correspondent</li>
<li>Rugby Correspondent</li>
<li>Football Correspondent</li>
<li>Hockey Correspondent</li>
<li>Indoor Sports Correspondent</li>


</ul>

<p class="text">This section of the newspaper is responsible for covering all the sporting activities carried out by the students and clubs of Trinity. <em>The University Times</em> focuses its attention on all aspects of sport in College, rather than on national and international sport. It aims to be the go-to place for everything happening in Trinity's sporting scene.</p>

<p class="text">Typically, candidates for the positions in this section have already written about sport or College-related news for <em>The University Times</em> or in other student publications. Experience in national publications will be considered, but experience in Trinity student media is preferred. </p>

<p class="text">Candidates for these positions should understand the workings of Dublin University Central Athletic Club (DUCAC) and Trinity's Sports Department, and be prepared to report at a high level on the inner workings of these institutions. They should also have connections in sports clubs.</p>

<p class="text">Candidates should work very well in a team, and should expect collaboration with a wide variety of journalists, whether they are writers, photographers, or editors. </p>

<p class="text">The correspondent positions, introduced three years ago, are an indication of the paper’s dedication to covering all sports, large and small, across campus. Successful candidates for the correspondent positions should expect to become the foremost experts on their respective sport/sports and will help lead our coverage of these sports. Correspondents should expect to develop a strong working relationship with Trinity’s sports clubs and teams throughout the year and successful candidates should be able to show a genuine passion for their chosen area.</p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 150,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for these positions should expect to be responsible for the production of several articles every week, and should expect very frequent work and interaction with the Editor and Deputy Editor.</p>
		
		
