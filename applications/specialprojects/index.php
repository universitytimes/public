<p class="text">The Special Projects Editor of <em>The University Times</em> takes responsibility for projects that the newspaper undertakes that are distinct from the regular output of the other sections. This  responsibility may include print supplements, such as the annual freshers' week supplement and the TCDSU elections supplement. However, candidates should view the role as an opportunity to create several, custom projects that are not restricted to the paper's print output.</p>
	
<p class="text">The Special Projects Editor will be in charge of the direction of these projects from inception to completion. It is up to the Special Projects Editor to come up with ideas that blend all of the newspaper's editorial resources &ndash; projects that use statistics, projects that might use online-only components, and projects that focus on a certain topic in depth, such as a running series on the website.</p>


<p class="text">Candidates for this position should expect to combine strategic, editorial and tactical responsibilities, and should be a big thinker who is also able to execute big ideas effectively.</p>

<p class="text">In particular, candidates should be comfortable writing and editing a wide variety of content types.</p>


<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 150,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for this should expect their work to be focused with that in mind, and as such, should expect work and time commitments that reflect the focus of a daily, student-run newspaper.</p>


		
		
