<p class="text">The Features section of <em>The University Times</em> currently has vacancies in the following positions:</p>


<ul class="listof">

<li>Features Editor</li>
<li>Deputy Features Editor</li>
<li>Assistant Features Editor</li>

</ul>

<p class="text">This section of the newspaper is responsible for in-depth articles that are written from a student perspective, normally about Trinity or student-related issues. Whether it is investigating a shooting in the Arts Block that <a href="https://www.universitytimes.ie/2019/10/in-1981-a-british-businessman-was-shot-in-the-arts-block-why-does-no-one-remember/">everyone seems to have forgotten</a>, examining the <a href="http://www.universitytimes.ie/2021/02/the-long-road-to-gender-equality-in-academia/">shortage of female leaders in academia</a> or looking at how the Trinity Access Programme <a href="http://www.universitytimes.ie/2021/03/how-tap-created-blueprints-for-equality-in-britains-elite-universities/"> was replicated in Oxford</a>, the Features section aims to answer questions by speaking to the people involved in something, doing the research, and pulling it all together into flowing prose.</p>

<p class="text">Typically, candidates for the positions in this section have already served as a Staff Writer or Senior Staff Writer in <em>The University Times</em> or in other student publications, or in a masthead position. Experience in national publications will be considered, but experience in Trinity student media is preferred. </p>

<p class="text">Candidates should work very well in a team, and should expect collaboration with a wide variety of journalists, whether they are writers, photographers, illustrators or editors. </p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 150,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for these positions should expect to be responsible for the production of several features articles every week, and should expect daily work and interaction with the Editor and Deputy Editor.</p>
		
		
