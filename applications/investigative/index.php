		<h3 class="lefth3">Investigative Editor</h3><a href="/applications/investigative/apply" class="apply">Apply for this Position</a> 
		
		<div class="clear"></div>
		
		<div class="details">
		
		<p class="text"><em>The University Times</em> is Ireland's largest student newspaper and the current holder of the Student Publication of the Year award. In everything we do, we strive to hold College and the Students' Union to account.</p>

<p class="text"><em>The University Times</em>'s the Investigative Editor is responsible for producing investigative pieces examining issues across the full spectrum of college life. This responsibility includes co-ordinating with section heads on long-term areas of interest they wish to develop, pursuing stories affecting students that might otherwise go unexplored and producing pieces that take an in-depth look at the activities of the College and its authorities, always with the intention of holding power accountable.</p>
	
<p class="text">These comprehensive, investigative pieces will require candidates to undertake independent research, determine and pursue an angle of inquiry, liaise with relevant parties and co-ordinate with photographers and other journalists.</p>


<p class="text">In particular, candidates should operate in tandem with the News Editor and the Special Projects Editor to shape the paper’s investigative agenda and to determine the areas of most pressing interest.</p>

<p class="text">While the role will entail a great deal of co-ordination with the newspaper’s senior masthead and specific section editors, it should also be seen as an exploratory opportunity. In lieu of a specific brief, the Investigative Editor will enjoy scope to pursue stories on their own initiative. Successful candidates will thus be required to operate autonomously, as they will have significant control of the development of a story from inception to completion.</p>

<p class="text">Candidates for this position should expect to combine editorial responsibilities with a focused, analytical approach to investigative reporting. In particular, candidates should be prepared to chase stories determinedly and consistently as well as creatively, in situations where information may not be readily available or forthcoming.</p>

<p class="text">An understanding of financial accounts and the College’s administrative and capitated bodies is helpful, but not essential.</p>

<p class="text">All candidates should expect to attend weekly news meetings, as well as meetings with relevant senior editors across other sections of the paper.</p>


<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 150,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for this should expect their work to be focused with that in mind, and as such, should expect work and time commitments that reflect the focus of a daily, student-run newspaper.</p>



	
		
		
