		<p class="text"><em>The University Times</em> is Ireland's largest student newspaper. In everything we do, we strive to hold College and Trinity College Dublin Students' Union to account.</p>

<p class="text">The Photo team of <em>The University Times</em> consists of the following positions:</p>


<ul class="listof">

<li>Photo Editor</li>
<li>Deputy Photo Editor</li>

</ul>


<p class="text">While it is generally expected that the photo editors themselves will be excellent photographers, a large part of the roles lie with sourcing other photographers and ensuring that <em>The University Times</em> has photographers there to cover current events in Trinity and in student life, and that a wide variety of original photojournalism is featured on the pages of the newspaper, online and in print.</p>

<p class="text">Thus, candidates for this section should have strong organisational and interpersonal skills, and should expect to attend weekly section meetings such that they are aware what events need photographing and which stories need accompanying photos. They should also expect to have to interact with editors from the features, opinion, sports, magazine and Radius sections on a daily basis, as well as very close collaboration with the Editor and Deputy Editor.</p>

<p class="text">The Photo Editor will also be responsible for photo content on our social media platforms. In recent years, Instagram has become an important channel for <em>The University Times</em> to reach its readers, and so it is important that candidates understand how best to use social media.</p>

<p class="text">Candidates for these positions should understand that photojournalism, the type of photography that appears in newspapers, is distinct from photography in general. The Photo Editor and Photo Deputy Editor of the <em>The University Times</em> should view themselves as journalists first and foremost – journalists that employ images in order to tell a news story in an honest, impartial way – and secondly, photographers. Thus, photographers that regularly have to rely on post-camera manipulation are not suitable for this position.</p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 150,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for this position should understand that their role will primarily be with an online focus.</p>
		
		
