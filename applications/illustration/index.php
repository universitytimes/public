<p class="text">The Illustrations Team of <em>The University Times</em> is responsible for organising the production of illustrations to supplement the content produced for our website and print newspaper.</p>

<p class="text">The Illustrations Team of <em>The University Times</em> consists of the following positions:</p>


<ul class="listof">

<li>Illustrations Editor</li>
<li>Deputy Illustrations Editor

</li>
</ul>


<p class="text">While it is generally expected that the Illustrations Editor and Deputy Illustrations Editor themselves will be excellent illustrators, the roles also involve sourcing other illustrators and ensuring that the content <em>The University Times</em> is adequately illustrated, where applicable.</p>

<p class="text">Thus, candidates for this section should have strong organisational and interpersonal skills, and should expect to attend weekly masthead meetings to liaise with the features, opinion, and magazine editors and determine which content needs companion illustrations.</p>

<p class="text">Candidates for this section should also expect close collaboration with the Editor, Deputy Editor and Assistant Editor.</p>

<p class="text">Candidates should understand that <em>The University Times</em> is an online-first newspaper. Our readership online, often reaching more than 150,000 people each month, has now by an order of magnitude overtaken our readership in print. As such, candidates for this section should understand that their role should come with an online-first focus.</p>
		
		
